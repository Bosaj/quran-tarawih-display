export const STRINGS: Record<Lang, Strings> = { ar, fr, en }

export function statusLabel(status: string, t: Strings): string {
  if (status === 'searching') return t.statusSearching
  if (status === 'locked') return t.statusLocked
  if (status === 'uncertain') return t.statusUncertain
  if (status === 'frozen') return t.statusFrozen
  return t.statusIdle
}

export function initialLang(): Lang {
  try {
    const saved = JSON.parse(localStorage.getItem('tarawih:lang') ?? 'null') as Lang | null
    if (saved && saved in STRINGS) return saved
  } catch {
    /* private window */
  }
  const nav = typeof navigator === 'undefined' ? 'ar' : navigator.language.slice(0, 2)
  return nav === 'fr' || nav === 'en' ? nav : 'ar'
}
